#!/usr/bin/env node
/**
 * Generate docs/PROFILE_TRUST_INVENTORY.md: for every profile, the constraints that matter, where
 * they come from, how far they can be trusted right now, when they must be re-checked, and what the
 * automated watch last saw.
 *
 *   node scripts/trust-inventory.mjs            write the document
 *   node scripts/trust-inventory.mjs --check     fail (exit 2) if the document is out of date
 *
 * Regenerated rather than hand-written, so it can never drift from the data.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { computeFreshness, METHOD_LABEL, reviewDueAt } from "../src/engine/profiles/verification.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const dataDir = resolve(root, "src/engine/profiles/data");
const outPath = resolve(root, "docs/PROFILE_TRUST_INVENTORY.md");

const MB = (n) => `${(n / 1_000_000).toFixed(n % 1_000_000 ? 1 : 0)} MB`;

function keyConstraints(p) {
  const bits = [`${p.ppi.preferred}/${p.ppi.minimum} PPI`];
  const inch = (v, u) => (u === "mm" ? `${v} mm` : `${v} in`);
  bits.push(`${inch(p.size.width, p.size.unit)} × ${inch(p.size.height, p.size.unit)}`);
  bits.push(p.accepted_formats.join("/").toUpperCase());
  if (p.max_file_size_bytes) {
    bits.push(p.max_file_size_bytes_upper && p.max_file_size_bytes_upper !== p.max_file_size_bytes
      ? `≤ ${MB(p.max_file_size_bytes)} (published ${Math.round(p.max_file_size_bytes_upper / 1024 / 1024)} MB, ambiguous)`
      : `≤ ${MB(p.max_file_size_bytes)}`);
  }
  if (p.bleed) {
    const sides = Object.entries(p.bleed.sides).filter(([, on]) => on).map(([k]) => k).join("/");
    bits.push(`bleed ${p.bleed.value} ${p.bleed.unit} (${sides})`);
  }
  if (p.line_art_ppi_multiplier > 1) bits.push(`line art ×${p.line_art_ppi_multiplier}`);
  if (p.transparency !== "flatten_to_white") bits.push(`transparency ${p.transparency}`);
  if (p.color.cmyk_accepted) bits.push("CMYK input accepted");
  return bits.join("; ");
}

function host(url) {
  try {
    return new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return "—";
  }
}

function row(id, constraints, source, watch, now) {
  const w = watch.sources.find((s) => s.url === source.source_url);
  const status = computeFreshness(source.review_status, source.source_type, source.verification, source.last_verified_at, w?.status, now);
  const due = reviewDueAt(source.source_type, source.verification, source.last_verified_at);
  const v = source.verification;
  const verified = v.method === "none"
    ? `never (recorded ${source.last_verified_at})`
    : `${v.verified_at} — ${METHOD_LABEL[v.method]}${v.verified_by ? `, ${v.verified_by}` : ""}`;
  return {
    id,
    constraints,
    sourceType: source.source_type,
    host: host(source.source_url),
    status,
    verified,
    due: v.method === "none" ? "**never verified**" : (due ?? "never expires"),
    watch: w ? w.status : "not watched",
    gap: v.method === "none" || status !== "current",
    evidence: v.evidence.length,
  };
}

function build(now = new Date()) {
  const watch = JSON.parse(readFileSync(resolve(dataDir, "source-watch.json"), "utf8"));
  const rows = [];
  for (const file of readdirSync(dataDir).sort()) {
    if (!file.endsWith(".json") || file === "source-watch.json") continue;
    const g = JSON.parse(readFileSync(resolve(dataDir, file), "utf8"));
    for (const p of g.profiles) {
      rows.push({ group: g.label, ...row(p.id, keyConstraints(p), p.source, watch, now) });
      if (p.constraints_source) {
        rows.push({
          group: g.label,
          ...row(`${p.id} → delivery limits`, `≤ ${MB(p.max_file_size_bytes)} per file`, p.constraints_source, watch, now),
        });
      }
    }
    const mc = g.marketplace_constraints;
    if (mc) {
      rows.push({
        group: g.label,
        ...row(`${g.destination} marketplace`,
          `${mc.max_files_per_listing} files/listing; ≤ ${MB(mc.max_file_size_bytes)} each; filenames ≤ ${mc.filename_max_length} chars`,
          mc.source, watch, now),
      });
    }
  }
  return { rows, watch };
}

function render({ rows, watch }, now) {
  const gaps = rows.filter((r) => r.gap);
  const byStatus = rows.reduce((acc, r) => ({ ...acc, [r.status]: (acc[r.status] ?? 0) + 1 }), {});
  const lines = [];
  lines.push("# Profile Trust Inventory");
  lines.push("");
  lines.push(`Generated by \`npm run trust:inventory\` on ${now.toISOString().slice(0, 10)}. Do not edit by hand.`);
  lines.push("");
  lines.push(`${rows.length} trust records across ${new Set(rows.map((r) => r.group)).size} destinations: ` +
    Object.entries(byStatus).map(([k, v]) => `**${v} ${k}**`).join(", ") + ".");
  lines.push("");
  lines.push("`status` is the trust state in effect right now: the stored state after the automated watch and the");
  lines.push("re-check deadline have been applied. Automation can only lower it.");
  lines.push("");
  let group = null;
  for (const r of rows) {
    if (r.group !== group) {
      group = r.group;
      lines.push("");
      lines.push(`## ${group}`);
      lines.push("");
      lines.push("| Profile | Key constraints | Source | Status | Verified | Review due | Watch | Evidence |");
      lines.push("|---|---|---|---|---|---|---|---|");
    }
    lines.push(`| \`${r.id}\` | ${r.constraints} | ${r.sourceType}<br>${r.host} | ${r.status === "current" ? "current" : `**${r.status}**`} | ${r.verified} | ${r.due} | ${r.watch} | ${r.evidence || "—"} |`);
  }
  lines.push("");
  lines.push("## Still missing a reliable source");
  lines.push("");
  if (gaps.length === 0) {
    lines.push("Nothing outstanding.");
  } else {
    lines.push("| Record | Why it is not trustworthy yet | What would fix it |");
    lines.push("|---|---|---|");
    for (const r of gaps) {
      const why = r.status === "unverified"
        ? `${r.host} refuses automated reading and no human has verified it`
        : r.status === "stale"
          ? `the last verification (${r.verified}) is past its review date (${r.due})`
          : r.status === "needs-review"
            ? `${r.host} changed since it was last verified`
            : "no verification record";
      lines.push(`| \`${r.id}\` | ${why} | Open ${r.host}, read the rule, then \`npm run verify:record -- --url … --method human_page_read --by "<name>" --quote "<verbatim sentence>" --supports <fields>\` |`);
    }
  }
  lines.push("");
  lines.push("## Automated watch");
  lines.push("");
  lines.push("| Source | Last checked | Watch status | Baseline |");
  lines.push("|---|---|---|---|");
  for (const s of watch.sources) {
    lines.push(`| ${host(s.url)} | ${s.lastChecked ?? "never"} | ${s.status}${s.note ? ` — ${s.note}` : ""} | ${s.verifiedHash ? `${s.baselineFrom ?? "recorded"} (${s.verifiedHash.slice(0, 12)}…)` : "none"} |`);
  }
  lines.push("");
  return lines.join("\n");
}

const now = new Date();
const text = render(build(now), now);
if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(outPath, "utf8");
    } catch {
      return "";
    }
  })();
  // The generation date changes daily; compare everything else.
  const strip = (t) => t.replace(/^Generated by .*$/m, "");
  if (strip(current) !== strip(text)) {
    console.error("docs/PROFILE_TRUST_INVENTORY.md is out of date. Run: npm run trust:inventory");
    process.exit(2);
  }
  console.log("trust inventory is up to date.");
} else {
  writeFileSync(outPath, text);
  console.log(`Wrote ${outPath}`);
}
